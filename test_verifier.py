import pyotp

SECRET = "GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ"
SECRET2 = "ABCDEFGHABCDEFGHABCDEFGH"


class OTPVerifierConstructionTest(unittest.TestCase):
    def test_rejects_base_otp_and_wrong_types(self):
        with self.assertRaisesRegex(TypeError, "HOTP, TOTP or Steam instance"):
            pyotp.OTPVerifier(pyotp.OTP(SECRET))
        with self.assertRaises(TypeError):
            pyotp.OTPVerifier("not-an-otp")  # type: ignore[arg-type]

    def test_window_and_watermark_validation(self):
        for value in (-1, -10, 1.5, "1", True, False):
            with self.subTest(value=value):
                with self.assertRaises(ValueError):
                    pyotp.OTPVerifier(pyotp.HOTP(SECRET), window=value)  # type: ignore[arg-type]
                with self.assertRaises(ValueError):
                    pyotp.OTPVerifier(pyotp.HOTP(SECRET), last_consumed=value)  # type: ignore[arg-type]
        # None is the legitimate "nothing consumed yet" watermark.
        verifier = pyotp.OTPVerifier(pyotp.HOTP(SECRET), last_consumed=None)
        self.assertIsNone(verifier.last_consumed)

    def test_default_watermark_is_none(self):
        verifier = pyotp.OTPVerifier(pyotp.HOTP(SECRET))
        self.assertIsNone(verifier.last_consumed)
        self.assertEqual(verifier.window, 0)
        self.assertIsInstance(verifier.otp, pyotp.HOTP)


class OTPVerifierDriftTest(unittest.TestCase):
    """Forward-window resynchronization across all three OTP forms."""

    def test_hotp_forward_scan_returns_actual_counter_and_advances(self):
        hotp = pyotp.HOTP(SECRET)
        verifier = pyotp.OTPVerifier(hotp, window=5)
        # The client skipped counters 10..12 and presents the code for 13.
        matched = verifier.verify(hotp.at(13), counter=10)
        self.assertEqual(matched, 13)
        self.assertEqual(verifier.last_consumed, 13)

    def test_hotp_window_upper_bound_is_caller_given(self):
        hotp = pyotp.HOTP(SECRET)
        verifier = pyotp.OTPVerifier(hotp)
        # Position 3 lies one step beyond the requested window of 2.
        with self.assertRaises(pyotp.OTPVerificationError):
            verifier.verify(hotp.at(3), counter=0, window=2)
        self.assertIsNone(verifier.last_consumed)
        # A per-call window cannot widen beyond what the caller passes.
        self.assertEqual(verifier.verify(hotp.at(3), counter=0, window=3), 3)

    def test_hotp_initial_count_offset_is_handled_internally(self):
        hotp = pyotp.HOTP(SECRET, initial_count=100)
        verifier = pyotp.OTPVerifier(hotp, window=3)
        # Caller coordinates stay relative; absolute HMAC input is 102.
        matched = verifier.verify(hotp.at(2), counter=0)
        self.assertEqual(matched, 2)
        self.assertEqual(verifier.last_consumed, 2)

    def test_totp_forward_scan_uses_timecodes(self):
        totp = pyotp.TOTP(SECRET2)
        verifier = pyotp.OTPVerifier(totp, window=2)
        # Base timecode 6 at t=200; client is two time steps ahead (timecode 8).
        matched = verifier.verify(totp.generate_otp(8), for_time=200)
        self.assertEqual(matched, 8)
        self.assertEqual(verifier.last_consumed, 8)

    def test_totp_time_step_conversion_respected(self):
        totp = pyotp.TOTP(SECRET2, interval=60)
        self.assertEqual(totp.timecode(3899), 64)
        verifier = pyotp.OTPVerifier(totp, window=2)
        matched = verifier.verify(totp.generate_otp(66), for_time=3899)
        self.assertEqual(matched, 66)
        self.assertEqual(verifier.last_consumed, 66)

    def test_steam_alphabet_and_time_step_inside_window(self):
        steam = pyotp.contrib.Steam(SECRET2)
        verifier = pyotp.OTPVerifier(steam, window=2)
        # Five-character custom alphabet codes are generated by Steam itself.
        code = steam.generate_otp(7)
        self.assertEqual(len(code), 5)
        self.assertTrue(set(code) <= set(pyotp.contrib.steam.STEAM_CHARS))
        matched = verifier.verify(code, for_time=200)  # base timecode 6
        self.assertEqual(matched, 7)
        self.assertEqual(verifier.last_consumed, 7)

    def test_per_call_window_overrides_default_without_mutating_it(self):
        totp = pyotp.TOTP(SECRET2)
        verifier = pyotp.OTPVerifier(totp, window=0)
        with self.assertRaises(pyotp.OTPVerificationError):
            verifier.verify(totp.generate_otp(7), for_time=200)
        self.assertEqual(verifier.verify(totp.generate_otp(7), for_time=200, window=1), 7)
        self.assertEqual(verifier.window, 0)

    def test_earliest_match_is_consumed_on_collision(self):
        totp = pyotp.TOTP(SECRET2)
        verifier = pyotp.OTPVerifier(totp, window=3)
        # First match within [6, 9] wins and the watermark stops there.
        matched = verifier.verify(totp.generate_otp(6), for_time=200)
        self.assertEqual(matched, 6)
        self.assertEqual(verifier.last_consumed, 6)

    def test_fullwidth_code_still_matches(self):
        hotp = pyotp.HOTP(SECRET)
        verifier = pyotp.OTPVerifier(hotp, window=1)
        fullwidth = hotp.at(2).translate(str.maketrans("0123456789", "０１２３４５６７８９"))
        self.assertEqual(verifier.verify(fullwidth, counter=1), 2)


class OTPVerifierReplayTest(unittest.TestCase):
    """Replay protection: consumed positions and earlier codes are rejected."""

    def test_hotp_same_position_rejected_then_later_position_accepted(self):
        hotp = pyotp.HOTP(SECRET)
        verifier = pyotp.OTPVerifier(hotp, window=5)
        self.assertEqual(verifier.verify(hotp.at(13), counter=10), 13)

        # Replaying the exact consumed code, even from a lower base counter.
        with self.assertRaises(pyotp.OTPReplayError):
            verifier.verify(hotp.at(13), counter=10)
        # An earlier code inside a freshly requested window is a replay too.
        with self.assertRaises(pyotp.OTPReplayError):
            verifier.verify(hotp.at(11), counter=11, window=5)
        # The next unused counter still succeeds and pushes the watermark on.
        self.assertEqual(verifier.verify(hotp.at(14), counter=14), 14)
        self.assertEqual(verifier.last_consumed, 14)

    def test_totp_replay_and_earlier_window_codes_rejected(self):
        totp = pyotp.TOTP(SECRET2)
        verifier = pyotp.OTPVerifier(totp, window=2)
        self.assertEqual(verifier.verify(totp.generate_otp(8), for_time=200), 8)

        # Same timecode presented again is a replay.
        with self.assertRaises(pyotp.OTPReplayError):
            verifier.verify(totp.generate_otp(8), for_time=200)
        # Earlier timecode 7 reached via a later base + window is rejected.
        with self.assertRaises(pyotp.OTPReplayError):
            verifier.verify(totp.generate_otp(7), for_time=200, window=3)
        # A genuinely new timecode is accepted.
        self.assertEqual(verifier.verify(totp.generate_otp(9), for_time=200, window=3), 9)

    def test_steam_replay_uses_same_semantics(self):
        steam = pyotp.contrib.Steam(SECRET2)
        verifier = pyotp.OTPVerifier(steam, window=2)
        self.assertEqual(verifier.verify(steam.generate_otp(7), for_time=200), 7)
        with self.assertRaises(pyotp.OTPReplayError):
            verifier.verify(steam.generate_otp(7), for_time=200)

    def test_replay_error_is_verification_error(self):
        hotp = pyotp.HOTP(SECRET)
        verifier = pyotp.OTPVerifier(hotp)
        verifier.verify(hotp.at(5), counter=5)
        with self.assertRaises(pyotp.OTPVerificationError):
            verifier.verify(hotp.at(5), counter=5)

    def test_watermark_restored_from_state_blocks_old_codes(self):
        hotp = pyotp.HOTP(SECRET)
        verifier = pyotp.OTPVerifier(hotp, window=10, last_consumed=20)
        with self.assertRaises(pyotp.OTPReplayError):
            verifier.verify(hotp.at(20), counter=15)
        self.assertEqual(verifier.verify(hotp.at(21), counter=15), 21)

    def test_wrong_code_does_not_advance_watermark(self):
        totp = pyotp.TOTP(SECRET2)
        verifier = pyotp.OTPVerifier(totp, window=2)
        with self.assertRaises(pyotp.OTPVerificationError):
            verifier.verify("000000", for_time=200)
        self.assertIsNone(verifier.last_consumed)
        self.assertEqual(verifier.verify(totp.generate_otp(6), for_time=200), 6)


class OTPVerifierBoundaryTest(unittest.TestCase):
    """Negative values, out-of-range windows and kind mismatches."""

    def test_negative_and_invalid_hotp_counter(self):
        verifier = pyotp.OTPVerifier(pyotp.HOTP(SECRET))
        for value in (-1, -100):
            with self.subTest(value=value):
                with self.assertRaisesRegex(ValueError, "non-negative integer"):
                    verifier.verify("123456", counter=value)
        for value in (1.0, True, "5"):
            with self.subTest(value=value):
                with self.assertRaises(ValueError):
                    verifier.verify("123456", counter=value)  # type: ignore[arg-type]

    def test_negative_per_call_window(self):
        hotp = pyotp.OTPVerifier(pyotp.HOTP(SECRET))
        totp = pyotp.OTPVerifier(pyotp.TOTP(SECRET2))
        with self.assertRaisesRegex(ValueError, "non-negative integer"):
            hotp.verify("123456", counter=0, window=-1)
        with self.assertRaisesRegex(ValueError, "non-negative integer"):
            totp.verify("123456", for_time=200, window=-2)

    def test_argument_kind_mismatch(self):
        hotp_verifier = pyotp.OTPVerifier(pyotp.HOTP(SECRET))
        totp_verifier = pyotp.OTPVerifier(pyotp.TOTP(SECRET2))
        with self.assertRaisesRegex(TypeError, "counter is required"):
            hotp_verifier.verify("123456")
        with self.assertRaisesRegex(TypeError, "for_time is only valid for TOTP"):
            hotp_verifier.verify("123456", counter=0, for_time=200)
        with self.assertRaisesRegex(TypeError, "counter is only valid for HOTP"):
            totp_verifier.verify("123456", counter=0)

    def test_totp_timestamp_out_of_range(self):
        verifier = pyotp.OTPVerifier(pyotp.TOTP(SECRET2))
        with self.assertRaisesRegex(ValueError, "for_time must be"):
            verifier.verify("123456", for_time=-1)
        with self.assertRaisesRegex(ValueError, "for_time must be"):
            verifier.verify("123456", for_time=253402300800)

    def test_window_fully_below_watermark_is_replay(self):
        hotp = pyotp.HOTP(SECRET)
        verifier = pyotp.OTPVerifier(hotp, window=0, last_consumed=9)
        with self.assertRaisesRegex(pyotp.OTPReplayError, "already been consumed"):
            verifier.verify(hotp.at(9), counter=9)

    def test_datetime_for_time_supported(self):
        totp = pyotp.TOTP(SECRET2)
        verifier = pyotp.OTPVerifier(totp)
        moment = datetime.datetime(1970, 1, 1, 0, 3, 20, tzinfo=datetime.timezone.utc)
        self.assertEqual(verifier.verify(totp.at(moment), for_time=moment), 6)


class OTPVerifierConcurrencyTest(unittest.TestCase):
    """Only one thread may consume a given position."""

    def _assert_single_winner(self, make_call, threads_count):
        barrier = threading.Barrier(threads_count)
        results: list[object] = []
        lock = threading.Lock()

        def worker():
            barrier.wait()
            try:
                result = make_call()
            except Exception as error:  # noqa: BLE001 - record every outcome
                result = error
            with lock:
                results.append(result)

        workers = [threading.Thread(target=worker) for _ in range(threads_count)]
        for thread in workers:
            thread.start()
        for thread in workers:
            thread.join()

        successes = [result for result in results if not isinstance(result, BaseException)]
        failures = [result for result in results if isinstance(result, pyotp.OTPVerificationError)]
        self.assertEqual(len(successes), 1)
        self.assertEqual(len(failures), threads_count - 1)
        self.assertTrue(all(isinstance(result, pyotp.OTPReplayError) for result in failures))

    def test_hotp_concurrent_same_counter(self):
        hotp = pyotp.HOTP(SECRET)
        verifier = pyotp.OTPVerifier(hotp, window=3)
        code = hotp.at(7)
        self._assert_single_winner(lambda: verifier.verify(code, counter=7), 12)
        self.assertEqual(verifier.last_consumed, 7)

    def test_totp_concurrent_same_timecode(self):
        totp = pyotp.TOTP(SECRET2)
        verifier = pyotp.OTPVerifier(totp, window=2)
        code = totp.generate_otp(6)
        # Fixed for_time keeps every thread competing for the same timecode.
        self._assert_single_winner(lambda: verifier.verify(code, for_time=200), 12)
        self.assertEqual(verifier.last_consumed, 6)

    def test_steam_concurrent_same_timecode(self):
        steam = pyotp.contrib.Steam(SECRET2)
        verifier = pyotp.OTPVerifier(steam, window=2)
        code = steam.generate_otp(6)
        self._assert_single_winner(lambda: verifier.verify(code, for_time=200), 8)
        self.assertEqual(verifier.last_consumed, 6)


class OTPVerifierStateTest(unittest.TestCase):
    """Serializable state for external storage."""

    def test_state_is_json_serializable_and_round_trips(self):
        hotp = pyotp.HOTP(SECRET)
        verifier = pyotp.OTPVerifier(hotp, window=4)
        verifier.verify(hotp.at(11), counter=10)

        encoded = json.dumps(verifier.to_state())
        restored = pyotp.OTPVerifier.from_state(hotp, json.loads(encoded))
        self.assertEqual(restored.window, 4)
        self.assertEqual(restored.last_consumed, 11)
        with self.assertRaises(pyotp.OTPReplayError):
            restored.verify(hotp.at(11), counter=10)
        self.assertEqual(restored.verify(hotp.at(12), counter=10), 12)

    def test_state_round_trips_for_totp_and_steam(self):
        for otp in (pyotp.TOTP(SECRET2, interval=60), pyotp.contrib.Steam(SECRET2)):
            with self.subTest(otp=type(otp).__name__):
                base = otp.timecode(200)
                target = base + 2
                verifier = pyotp.OTPVerifier(otp, window=3)
                verifier.verify(otp.generate_otp(target), for_time=200)
                restored = pyotp.OTPVerifier.from_state(otp, json.loads(json.dumps(verifier.to_state())))
                self.assertEqual(restored.last_consumed, target)
                with self.assertRaises(pyotp.OTPReplayError):
                    restored.verify(otp.generate_otp(target), for_time=200)

    def test_pickle_round_trip(self):
        totp = pyotp.TOTP(SECRET2)
        verifier = pyotp.OTPVerifier(totp, window=2, last_consumed=5)
        restored = pickle.loads(pickle.dumps(verifier))
        self.assertEqual(restored.window, 2)
        self.assertEqual(restored.last_consumed, 5)
        self.assertEqual(restored.verify(totp.generate_otp(6), for_time=200), 6)

    def test_malformed_state_rejected(self):
        hotp = pyotp.HOTP(SECRET)
        bad_states = [
            {"window": 1, "last_consumed": None},
            {"version": 1, "last_consumed": None},
            {"version": 1, "window": 1},
            {"version": 999, "window": 1, "last_consumed": None},
            {"version": "1", "window": 1, "last_consumed": None},
        ]
        for state in bad_states:
            with self.subTest(state=state):
                with self.assertRaises(ValueError):
                    pyotp.OTPVerifier.from_state(hotp, state)
        with self.assertRaises(ValueError):
            pyotp.OTPVerifier.from_state(hotp, "not-a-mapping")  # type: ignore[arg-type]
        with self.assertRaises(TypeError):
            pyotp.OTPVerifier.from_state(pyotp.OTP(SECRET), {"version": 1, "window": 0, "last_consumed": None})

    def test_fresh_state_contains_only_json_types(self):
        state = pyotp.OTPVerifier(pyotp.HOTP(SECRET)).to_state()
        self.assertEqual(state, {"version": 1, "window": 0, "last_consumed": None})
        json.dumps(state)


class LegacyVerificationUnchangedTest(unittest.TestCase):
    """The pre-resync interfaces keep their return values and exceptions."""

    def test_hotp_verify_still_stateless_boolean(self):
        hotp = pyotp.HOTP(SECRET)
        self.assertTrue(hotp.verify(hotp.at(9), 9))
        self.assertTrue(hotp.verify(hotp.at(9), 9))  # no replay tracking
        self.assertFalse(hotp.verify(hotp.at(9), 10))

    def test_totp_verify_still_stateless_boolean(self):
        totp = pyotp.TOTP(SECRET2)
        self.assertTrue(totp.verify("549250", for_time=200, valid_window=1))
        self.assertTrue(totp.verify("549250", for_time=200, valid_window=1))
        self.assertFalse(totp.verify("449527", for_time=200, valid_window=1))

    def test_verify_and_get_timecode_unchanged(self):
        totp = pyotp.TOTP(SECRET2)
        self.assertEqual(totp.verify_and_get_timecode("823229", for_time=200), 6)
        self.assertEqual(totp.verify_and_get_timecode("823229", for_time=200), 6)
        with self.assertRaises(pyotp.OTPVerificationError):
            totp.verify_and_get_timecode("000000", for_time=200)
        with self.assertRaisesRegex(ValueError, "valid_window cannot be negative"):
            totp.verify_and_get_timecode("823229", for_time=200, valid_window=-1)

    def test_steam_legacy_verify_unchanged(self):
        steam = pyotp.contrib.Steam(SECRET2)
        code = steam.at(200)
        self.assertTrue(steam.verify(code, for_time=200))
        self.assertTrue(steam.verify(code, for_time=200))
        self.assertEqual(steam.verify_and_get_timecode(code, for_time=200), 6)


